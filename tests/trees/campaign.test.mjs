import { readFileSync, existsSync } from 'node:fs'
import { test } from 'node:test'
import assert from 'node:assert/strict'
const root=new URL('../../',import.meta.url)
const api=readFileSync(new URL('public/api/trees/index.php',root),'utf8')
const ui=readFileSync(new URL('src/pages/PunjabTrees.tsx',root),'utf8')
const registry=readFileSync(new URL('src/data/routeRegistry.mjs',root),'utf8')
const policies=readFileSync(new URL('src/pages/LegalTrust.tsx',root),'utf8')
test('campaign uses a separate session and secure unique duplicate prevention',()=>{
  assert.match(api,/const TREE_SESSION = 'cssv_tree_session'/)
  assert.match(api,/UNIQUE KEY uq_tree_mobile \(mobile\)/)
  assert.match(api,/UNIQUE KEY uq_tree_cnic \(cnic_hash\)/)
  assert.match(api,/cssv_hash_secret\('tree-cnic:'\.\$cnic\)/)
  assert.doesNotMatch(api,/cnic_plaintext\s/)
})
test('only manually approved saplings count toward the 100-million-tree goal',()=>{
  assert.match(api,/const TREE_TARGET = 100000000/)
  assert.match(api,/function tree_rollup_adjust/)
  assert.match(api,/tree_campaign_city_rollup/)
  assert.match(api,/tree_campaign_member_rollup/)
  assert.match(api,/\$decision==='approved'\?1:-1/)
  assert.match(api,/WHERE status='approved'/)
  assert.match(api,/status ENUM\('pending','approved','rejected'\) NOT NULL DEFAULT 'pending'/)
  assert.match(api,/WHERE id=\? AND status=\?/)
})
test('photos are stored privately, restricted, consented and compressed',()=>{
  assert.match(api,/cssv_private_storage_dir\(\$folder\)/)
  assert.match(api,/const TREE_MAX_AVATAR = 40960/)
  assert.match(api,/const TREE_MAX_PROOF = 71680/)
  assert.match(api,/public_photo=1/)
  assert.match(ui,/const sanitized = await new Promise<Blob>/)
  assert.match(ui,/compressPhoto\(file,40\)/)
  assert.match(ui,/compressPhoto\(image,70\)/)
})
test('campaign form includes consent and private account protections',()=>{
  assert.match(ui,/type="checkbox" required checked=\{consent\}/)
  assert.match(ui,/onSigned\(data.member,data.csrf_token\)/)
  assert.match(api,/return \$csrf;/)
  assert.match(api,/hash_equals\(\$cookie,\$header\)/)
  assert.match(api,/cssv_require_separate_admin\(\$db\)/)
})
test('campaign remains ad-free, staged and disclosed under privacy policy',()=>{
  assert.match(registry,/publicPage\('\/100-million-trees'/)
  assert.match(registry,/contentQuality: 'interactive', adMode: 'disabled', indexable: false/)
  assert.match(policies,/CNIC/)
  assert.match(policies,/Isarul Ibaad Foundation/)
  assert.ok(existsSync(new URL('public/images/esar-ul-ebad-logo.webp',root)))
  assert.match(ui,/ISARUL IBAAD FOUNDATION.*CSS VISTA/)
  assert.match(ui,/className="trees-foundation-brand"/)
})
test('server never trusts client-only image compression or EXIF handling',()=>{
  assert.match(api,/imagecreatefromstring/)
  assert.match(api,/imagejpeg\(\$canvas,\$path/)
  assert.match(api,/tree_image_phash/)
  assert.match(api,/tree_phash_distance/)
  assert.match(api,/duplicate_risk/)
  assert.match(api,/cssv_private_storage_dir\(\$folder\)/)
})
test('secure offline recovery without SMS OTP and irreversible credential rotation',()=>{
  assert.match(api,/function tree_recovery_new/)
  assert.match(api,/random_bytes\(24\)/)
  assert.match(api,/tree_recovery_hash/)
  assert.match(api,/UPDATE tree_campaign_sessions SET revoked_at=NOW\(6\)/)
  assert.match(api,/\$action==='recover'/)
  assert.match(api,/\$action==='delete-account'/)
  assert.match(ui,/RecoveryKeyPanel/)
  assert.doesNotMatch(ui,/SMS OTP required/)
})
test('fraud review cannot approve suspicious reports without field verification',()=>{
  assert.match(api,/field_check_required/)
  assert.match(api,/tree_campaign_reviews/)
  assert.match(api,/field_visit_date/)
  assert.match(api,/\$decision==='revoked'/)
  assert.match(ui,/Revoke approval if fraudulent/)
})

test('survival reporting requires approved saplings and review',()=>{
  assert.match(api,/tree_campaign_followups/)
  assert.match(api,/in_array\(\$phase,\[30,90,180\],true\)/)
  assert.match(api,/status='approved'/)
  assert.match(api,/old_photo_reused/)
  assert.match(api,/followup-review/)
  assert.match(ui,/SurvivalCheckForm/)
  assert.match(ui,/Survival observations awaiting review/)
})
test('transactional counters cannot count revoked or deleted reports',()=>{
  assert.match(api,/function tree_rollup_adjust/)
  assert.match(api,/SELECT .*?tree_campaign_member_rollup/)
  assert.match(api,/SELECT .*?tree_campaign_city_rollup/)
  assert.match(api,/FOR UPDATE/)
  assert.match(api,/account_no_longer_exists/)
  assert.match(api,/tree_campaign_reviews/)
})
test('private data and owner decisions stay separated from public data',()=>{
  assert.match(api,/consent_version/)
  assert.match(api,/cnic_hash CHAR\(64\)/)
  assert.match(api,/recovery_hash CHAR\(64\)/)
  assert.match(api,/mobile_masked/)
  assert.match(api,/public_photo=1/)
  assert.match(api,/cssv_require_separate_admin/)
  assert.match(ui,/ISARUL IBAAD FOUNDATION/)
  assert.match(ui,/No SMS OTP or payment required/)
})
