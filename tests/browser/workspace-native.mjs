import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { isolateNetwork } from './isolated-network.mjs'
if(process.env.CI!=='true'||process.env.CSSV_DB_NAME!=='cssvista_briefing_test') throw Error('Disposable database required')
const base=process.env.CSSV_TEST_BROWSER_ORIGIN||'https://localhost:3444'
if(!['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw Error('Loopback only')
const env={...process.env};for(const k of ['DOCKER_HOST','DOCKER_CONTEXT','DOCKER_TLS','DOCKER_TLS_VERIFY','DOCKER_CERT_PATH'])delete env[k]
const php=(...args)=>execFileSync('docker',['--host=unix:///var/run/docker.sock','exec',process.env.CSSV_TEST_PHP_CONTAINER,'php',...args],{env,encoding:'utf8'}).trim()
const email=`workspace-native-${Date.now()}@example.invalid`
php('tests/current-affairs/setup.php','user',email)
const browser=await chromium.launch({executablePath:process.env.CSSV_BROWSER_EXECUTABLE||'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:390,height:960},reducedMotion:'reduce'})
await isolateNetwork(context,base)
const page=await context.newPage();page.setDefaultTimeout(30000)
try{
 await page.goto(base+'/account')
 await page.getByLabel('Email address',{exact:true}).fill(email)
 await page.getByLabel('Password',{exact:true}).fill('TEST ONLY native fixture password')
 await page.getByRole('button',{name:'Sign in securely',exact:true}).click()
 await page.waitForURL('**/account/dashboard')
 await page.getByRole('heading',{name:'Today’s Study Plan',exact:true}).waitFor()
 await page.goto(base+'/account/plan')
 await page.getByRole('heading',{name:'My Study Dashboard',exact:true}).waitFor()
 await page.getByText('Not set',{exact:true}).waitFor()
 await page.getByLabel('Target examination date',{exact:true}).fill('2027-12-01')
 const sample=['Political Science','Criminology','European History','Punjabi','Environmental Sciences']
 for(const name of sample)await page.getByRole('checkbox',{name,exact:true}).check()
 await page.getByRole('checkbox',{name:'Political Science',exact:true}).focus()
 await page.keyboard.press('Space')
 assert.equal(await page.getByRole('button',{name:'Save settings',exact:true}).isDisabled(),true)
 await page.keyboard.press('Space')
 await page.getByRole('button',{name:'Save settings',exact:true}).click()
 assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('cssvista:v1')).studyPlanner.selectedOptionals.slice().sort()),sample.slice().sort())
 await page.goto(base+'/account/subjects')
 for(const name of sample)await page.getByRole('heading',{name,exact:true}).waitFor()
 await page.goto(base+'/account/settings')
 const saved=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/student/progress.php'&&r.request().method()==='PUT')
 await page.getByRole('button',{name:'Sync progress now',exact:true}).click()
 assert.equal((await saved).status(),200)
 const remote=await (await context.request.get(base+'/api/student/progress.php')).json()
 assert.deepEqual(remote.payload['cssvista:v1'].studyPlanner.selectedOptionals.slice().sort(),sample.slice().sort())
 // A fresh browser context restores the selected subjects through native sync.
 const second=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:960}})
 await isolateNetwork(second,base)
 const login=await second.request.post(base+'/api/auth/login.php',{data:{email,password:'TEST ONLY native fixture password'}})
 assert.equal(login.status(),200)
 await second.route('**/api/student/progress.php',async route => { await new Promise(resolve=>setTimeout(resolve,1000)); await route.continue() })
 const other=await second.newPage()
 await other.goto(base+'/account/subjects')
 for(const name of sample)await other.getByRole('heading',{name,exact:true}).waitFor()
 await second.close()
 page.on('dialog',dialog=>dialog.accept())
 await page.goto(base+'/answer-timer')
 await page.getByRole('button',{name:'Start',exact:true}).click()
 await page.getByRole('button',{name:'Pause',exact:true}).waitFor()
 const initialTime=await page.getByRole('timer',{name:'Time remaining'}).textContent()
 await page.waitForTimeout(1100)
 await page.getByRole('link',{name:'Return to my preparation workspace',exact:true}).click()
 await page.getByRole('heading',{name:'Today’s Study Plan',exact:true}).waitFor()
 await page.goto(base+'/answer-timer')
 await page.getByRole('button',{name:'Pause',exact:true}).waitFor()
 await page.reload()
 await page.getByRole('button',{name:'Pause',exact:true}).waitFor()
 assert.notEqual(await page.getByRole('timer',{name:'Time remaining'}).textContent(),initialTime)
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 await page.goto(base+'/account/settings')
 await page.getByRole('button',{name:'Sign out',exact:true}).click()
 await page.waitForURL(/\/account(?:\?|$)/)
 assert.equal(await page.locator('.student-workspace').count(),0)
 console.log('PASS native workspace: real sign-in, optional settings save, subject navigation, account sync, delayed fresh-context restoration, timer navigation/refresh continuity and sign-out.')
}finally{await browser.close()}
