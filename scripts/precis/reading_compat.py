"""Keep earlier positional reading IDs separate from the restored book."""
import hashlib
import json


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def units(chapters):
    result = []
    for chapter in chapters:
        section = chapter['title'].split('. ', 1)[-1] if chapter['id'].isdigit() and int(chapter['id']) <= 22 else chapter['title']
        group = []
        start = 0
        def flush():
            if group:
                result.append({'id': f'{chapter["id"]}:{start}', 'chapter_id': chapter['id'],
                               'section': section, 'sha256': digest(group)})
                group.clear()
        for index, block in enumerate(chapter['blocks']):
            if block['type'] == 'heading':
                flush()
                section = block['text']
                continue
            if not group:
                start = index
            group.append(block)
            if len(group) == 3:
                flush()
        flush()
    return result


def compatibility(previous, current):
    old, new = units(previous['chapters']), units(current['chapters'])
    for unit in old:
        matches = [candidate for candidate in new if candidate['chapter_id'] == unit['chapter_id'] and candidate['sha256'] == unit['sha256']]
        unit['matched_unit_id'] = matches[0]['id'] if len(matches) == 1 else None
    return {'legacy_source_sha256': previous['source_sha256'],
            'legacy_content_sha256': digest({'title': previous['title'], 'front_matter': previous.get('front_matter', []), 'chapters': previous['chapters']}),
            'current_content_sha256': current['content_sha256'], 'units': old}


def php_compat(data):
    return "<?php\ndeclare(strict_types=1);\n// Generated by scripts/precis/check-handbook.py; earlier reading IDs are not current IDs.\nreturn json_decode(<<<'COMPAT'\n" + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + "\nCOMPAT, true, 64, JSON_THROW_ON_ERROR);\n"
