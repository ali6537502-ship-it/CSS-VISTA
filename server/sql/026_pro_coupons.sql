-- Additive only. Coupon allocations never impersonate payment receipts.
CREATE TABLE IF NOT EXISTS pro_coupons (
 id CHAR(36) NOT NULL PRIMARY KEY,
 request_id CHAR(36) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 code_hash CHAR(64) NOT NULL,
 label VARCHAR(120) NOT NULL,
 kind VARCHAR(24) NOT NULL,
 discount_value INT UNSIGNED NOT NULL,
 target_user_id CHAR(36) NULL,
 max_uses INT UNSIGNED NOT NULL,
 expires_at DATETIME(6) NOT NULL,
 disabled_at DATETIME(6) NULL,
 disabled_by CHAR(36) NULL,
 created_by CHAR(36) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY coupon_code_hash (code_hash),
 UNIQUE KEY coupon_admin_request (created_by,request_id),
 CONSTRAINT coupon_target_fk FOREIGN KEY (target_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT coupon_disabled_admin_fk FOREIGN KEY (disabled_by) REFERENCES admin_accounts(id) ON DELETE RESTRICT,
 CONSTRAINT coupon_admin_fk FOREIGN KEY (created_by) REFERENCES admin_accounts(id) ON DELETE RESTRICT,
 CONSTRAINT coupon_kind_chk CHECK ((kind='percent' AND discount_value BETWEEN 1 AND 99) OR (kind='fixed' AND discount_value>0) OR (kind='complimentary' AND discount_value=0)),
 CONSTRAINT coupon_limit_chk CHECK (max_uses BETWEEN 1 AND 10000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS pro_coupon_redemptions (
 id CHAR(36) NOT NULL PRIMARY KEY,
 coupon_id CHAR(36) NOT NULL,
 user_id CHAR(36) NOT NULL,
 request_id CHAR(36) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 order_id CHAR(36) NULL,
 base_amount_minor INT UNSIGNED NOT NULL,
 amount_minor INT UNSIGNED NOT NULL,
 activated_at DATETIME(6) NULL,
 starts_at DATETIME(6) NULL,
 expires_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY coupon_student_request (user_id,request_id),
 UNIQUE KEY coupon_order (order_id),
 KEY coupon_usage (coupon_id,user_id),
 KEY coupon_history (user_id,created_at),
 CONSTRAINT coupon_redemption_coupon_fk FOREIGN KEY (coupon_id) REFERENCES pro_coupons(id) ON DELETE RESTRICT,
 CONSTRAINT coupon_redemption_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT coupon_redemption_order_fk FOREIGN KEY (order_id) REFERENCES pro_orders(id) ON DELETE RESTRICT,
 CONSTRAINT coupon_redemption_amount_chk CHECK (base_amount_minor>0 AND amount_minor<base_amount_minor),
 CONSTRAINT coupon_redemption_period_chk CHECK ((order_id IS NOT NULL AND amount_minor>0 AND activated_at IS NULL AND starts_at IS NULL AND expires_at IS NULL) OR (order_id IS NULL AND amount_minor=0 AND activated_at IS NOT NULL AND starts_at IS NOT NULL AND expires_at>starts_at))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
